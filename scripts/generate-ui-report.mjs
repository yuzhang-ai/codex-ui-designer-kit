import { promises as fs } from 'node:fs';
import path from 'node:path';

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (!arg.startsWith('--')) continue;
    const [key, inline] = arg.slice(2).split('=');
    args[key] = inline ?? argv[++i] ?? true;
  }
  return args;
}

async function readIfExists(file) {
  try {
    return await fs.readFile(file, 'utf8');
  } catch {
    return '';
  }
}

function section(title, body) {
  return `## ${title}\n\n${body.trim() || '- Not provided.'}\n`;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const caseDir = path.resolve(String(args.caseDir || args.dir || '.'));
  const designDir = path.resolve(String(args.designDir || path.join(caseDir, '.design')));
  const outFile = path.resolve(String(args.out || path.join(caseDir, 'UI_DELIVERY_REPORT.md')));

  const audit = await readIfExists(path.join(caseDir, 'UI_AUDIT.md'));
  const design = await readIfExists(path.join(caseDir, 'DESIGN.md'));
  const qa = await readIfExists(path.join(designDir, 'UI_QA_REPORT.md'));
  const comparison = await readIfExists(path.join(designDir, 'BEFORE_AFTER_REPORT.md'));

  const report = `# UI DELIVERY REPORT

Generated by Codex UI Designer Kit.

${section('Audit Summary', audit.split('\n').slice(0, 40).join('\n'))}
${section('Design Summary', design.split('\n').slice(0, 50).join('\n'))}
${section('Visual QA', qa.split('\n').slice(0, 80).join('\n'))}
${section('Before / After', comparison.split('\n').slice(0, 60).join('\n'))}
## Human Review Required

- [ ] Confirm screenshots contain no customer data, secrets, account info, or internal URLs.
- [ ] Confirm any export, bulk send, delete, writeback, permission, or external-link action has a human confirmation gate.
- [ ] Confirm final copy, dates, links, recipients, and downloadable assets before external use.

## Follow-Up

- Add interactive state screenshots when the app supports them: loading, empty, error, disabled, hover, selected.
- Add more domain-specific reference rules if this UI belongs to a regulated or customer-data-heavy workflow.
`;

  await fs.writeFile(outFile, report, 'utf8');
  console.log(JSON.stringify({
    report: path.relative(process.cwd(), outFile).replaceAll('\\', '/'),
    used: {
      audit: Boolean(audit),
      design: Boolean(design),
      qa: Boolean(qa),
      comparison: Boolean(comparison),
    },
  }, null, 2));
}

main().catch(error => {
  console.error(error.message || error);
  process.exitCode = 1;
});
